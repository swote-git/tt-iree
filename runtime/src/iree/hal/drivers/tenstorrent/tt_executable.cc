  target->storage_shape[1] = ttex_ns(TensorDesc_storage_shape_1(source));
  target->storage_shape[2] = ttex_ns(TensorDesc_storage_shape_2(source));
  target->storage_shape[3] = ttex_ns(TensorDesc_storage_shape_3(source));
