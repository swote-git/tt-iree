// Vtable: export_info
//===----------------------------------------------------------------------===//

static iree_status_t iree_hal_tt_executable_export_info(
    iree_hal_executable_t *base_executable,
    iree_hal_executable_export_ordinal_t export_ordinal,
    iree_hal_executable_export_info_t *out_info) {
  iree_hal_tt_executable_t *executable =
      iree_hal_tt_executable_cast(base_executable);
  if (!out_info) {
    return iree_make_status(IREE_STATUS_INVALID_ARGUMENT, "out_info is null");
  }
  if (export_ordinal >= executable->entry_point_count) {
    return iree_make_status(IREE_STATUS_OUT_OF_RANGE,
                            "export ordinal %u out of range (count=%zu)",
                            export_ordinal, executable->entry_point_count);
  }

  const iree_hal_tt_entry_point_t *ep =
      &executable->entry_points[export_ordinal];
  memset(out_info, 0, sizeof(*out_info));
  out_info->name = ep->name;
  out_info->flags = (iree_hal_executable_export_flags_t)ep->flags;
  out_info->constant_count = ep->constant_count;
  out_info->binding_count = ep->binding_count;
  out_info->workgroup_size[0] = ep->workgroup_size[0];
  out_info->workgroup_size[1] = ep->workgroup_size[1];
  out_info->workgroup_size[2] = ep->workgroup_size[2];
  return iree_ok_status();
}

//===----------------------------------------------------------------------===//
// Vtable: export_parameters
//===----------------------------------------------------------------------===//

static iree_status_t iree_hal_tt_executable_export_parameters(
    iree_hal_executable_t *base_executable,
    iree_hal_executable_export_ordinal_t export_ordinal,
    iree_host_size_t capacity,
    iree_hal_executable_export_parameter_t *out_parameters) {
  iree_hal_tt_executable_t *executable =
      iree_hal_tt_executable_cast(base_executable);
  if (export_ordinal >= executable->entry_point_count) {
    return iree_make_status(IREE_STATUS_OUT_OF_RANGE,
                            "export ordinal %u out of range", export_ordinal);
  }

  // PoC: report 0 parameters.  The constant_count and binding_count in
  // export_info are sufficient for IREE's dispatch validation.  Detailed
  // parameter descriptors (names, types) can be added when needed.
  (void)capacity;
  (void)out_parameters;
  return iree_ok_status();
}

//===----------------------------------------------------------------------===//
// Vtable: lookup_export_by_name
//===----------------------------------------------------------------------===//

static iree_status_t iree_hal_tt_executable_lookup_export_by_name(
    iree_hal_executable_t *base_executable, iree_string_view_t name,
    iree_hal_executable_export_ordinal_t *out_export_ordinal) {
  iree_hal_tt_executable_t *executable =
      iree_hal_tt_executable_cast(base_executable);
  if (!out_export_ordinal) {
    return iree_make_status(IREE_STATUS_INVALID_ARGUMENT,
                            "out_export_ordinal is null");
  }

  for (iree_host_size_t i = 0; i < executable->entry_point_count; ++i) {
    if (iree_string_view_equal(name, executable->entry_points[i].name)) {
      *out_export_ordinal = (iree_hal_executable_export_ordinal_t)i;
      return iree_ok_status();
    }
  }
  return iree_make_status(IREE_STATUS_NOT_FOUND, "export '%.*s' not found",
                          (int)name.size, name.data);
}

//===----------------------------------------------------------------------===//
// Destroy
//===----------------------------------------------------------------------===//

static void
iree_hal_tt_executable_destroy(iree_hal_executable_t *base_executable) {
  iree_hal_tt_executable_t *executable =
      iree_hal_tt_executable_cast(base_executable);

#ifndef TT_IREE_ENABLE_MOCK
  for (iree_host_size_t i = 0; i < executable->entry_point_count; ++i) {
    iree_hal_tt_kernel_params_t *kp =
        &executable->entry_points[i].kernel_params;
    if (kp->program) {
      delete static_cast<tt::tt_metal::Program *>(kp->program);
      kp->program = NULL;
    }
  }
#endif

  for (iree_host_size_t i = 0; i < executable->entry_point_count; ++i) {
    iree_hal_tt_cleanup_aot_artifacts(
        executable->host_allocator, &executable->entry_points[i].kernel_params);
  }

  // Free owned FlatBuffer copy
  if (executable->owned_data) {
    iree_allocator_free(executable->host_allocator, executable->owned_data);
  }

  iree_allocator_free(executable->host_allocator, executable);
}

