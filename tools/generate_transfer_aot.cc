#include <cstdio>
#include <filesystem>
#include <fstream>
#include <iomanip>
#include <string>

#include "TenstorrentAOTCompiler.h"

using namespace mlir::iree_compiler::IREE::HAL;

int main(int argc, char **argv) {
  if (argc != 2)
    return 1;
  // Never leave a valid-looking partial generated source after an AOT failure.
  const std::filesystem::path target(argv[1]),
      temporary(target.string() + ".tmp");
  std::ofstream out(temporary);
  out << "// Generated by tt-iree-transfer-aot. Do not edit.\n"
         "#include \"iree/hal/drivers/tenstorrent/tt_fill_aot.h\"\n"
         "namespace iree::hal::tenstorrent { namespace {\n";
  for (const auto arch : {TenstorrentAOTTargetArch::WormholeB0,
                          TenstorrentAOTTargetArch::Blackhole}) {
    TenstorrentAOTKernelBundle bundle;
    std::string error;
    if (!compileFillAOT(arch, bundle, error) || bundle.kernels.size() != 1 ||
        bundle.artifacts.empty()) {
      std::fprintf(stderr, "fill AOT compilation failed: %s\n", error.c_str());
      out.close();
      std::filesystem::remove(temporary);
      return 1;
    }
    const unsigned id = static_cast<unsigned>(arch);
    for (size_t i = 0; i < bundle.artifacts.size(); ++i) {
      out << "const uint8_t data_" << id << '_' << i << "[] = {\n";
      for (size_t j = 0; j < bundle.artifacts[i].data.size(); ++j) {
        out << unsigned(bundle.artifacts[i].data[j]) << ',';
        if (j % 32 == 31)
          out << '\n';
      }
      out << "};\n";
    }
    out << "const FillAOTArtifact artifacts_" << id << "[] = {\n";
    for (size_t i = 0; i < bundle.artifacts.size(); ++i) {
      out << '{' << std::quoted(bundle.artifacts[i].path) << ", data_" << id
          << '_' << i << ", sizeof(data_" << id << '_' << i << ")},\n";
    }
    out << "};\nconst FillAOTBundle bundle_" << id << " = {R\"ttfill("
        << bundle.kernels[0].source << ")ttfill\", artifacts_" << id
        << ", sizeof(artifacts_" << id << ")/sizeof(FillAOTArtifact)};\n";
  }
  out << "} const FillAOTBundle* GetFillAOTBundle(uint8_t arch) {\n"
         "switch (arch) { case 1: return &bundle_1; case 2: return &bundle_2;\n"
         "default: return nullptr; }} }\n";
  out.close();
  if (!out) {
    std::filesystem::remove(temporary);
    return 1;
  }
  std::filesystem::rename(temporary, target);
  return 0;
}
